"""
Per-state summary of the county sweep: one chart row per state, one marker per algorithm.

Usage (from the repo root, after `python -m utils.graph_metrics`)
  python -m utils.state_summary

Reads results/county_metrics.csv and writes
  results/state_summary.csv               one row per state: size, largest clique, runtime per algorithm
  results/state_summary.md                the same as a readable table
  results/figures/state_runtime_census.png  Census adjacency graphs (queen)
  results/figures/state_runtime_rook.png    TIGER rook graphs (shared border >= 100 m)
"""

from pathlib import Path

import pandas as pd

from utils.graph_metrics import ALGOS, COLORS, FIGS, GRID, INK, MARKERS, METRICS, MUTED

RESULTS = Path("results")
LABELS = {"census": "Census adjacency (counties touching at a corner count as neighbours)",
          "tiger": "TIGER rook (counties must share at least 100 m of border)"}


def summary_table(df):
    """Wide table: one row per state, census and rook side by side."""
    rows = []
    for state, g in df.groupby("state", sort=False):
        c = g[g["source"] == "census"].iloc[0]
        r = g[g["source"] == "tiger"].iloc[0]
        row = {
            "state": state,
            "counties": int(c["n"]),
            "edges_census": int(c["m"]),
            "edges_rook": int(r["m"]),
            "largest_clique_census": int(c["omega"]),
            "largest_clique_rook": int(r["omega"]),
            "colors_needed_census": int(c["chi"]),
            "colors_needed_rook": int(r["chi"]),
        }
        for src, x in (("census", c), ("rook", r)):
            for a in ALGOS:
                ms = x[f"ms_{a}"]
                row[f"ms_{a}_{src}"] = "timeout" if pd.isna(ms) else round(float(ms), 4)
        rows.append(row)
    return pd.DataFrame(rows).sort_values("counties", ascending=False)


def markdown(t):
    def ms(v):
        if v == "timeout":
            return "timeout (>60 s)"
        return f"{v:.3f}" if v < 10 else f"{v:.1f}"

    head = ["state", "counties", "edges", "largest clique", "colors needed", *ALGOS]
    lines = [
        "# County maps by state",
        "",
        "Generated by `python -m utils.state_summary` from `county_metrics.csv`.",
        "",
        "Graph: the Census adjacency graph, where counties touching at a corner count as",
        "neighbours. The rook columns are in `state_summary.csv`. Runtimes are the median time in",
        "milliseconds of one coloring call over 21 runs, on one machine.",
        "",
        "| " + " | ".join(head) + " |",
        "|" + "---|" * len(head),
    ]
    for _, r in t.iterrows():
        lines.append("| " + " | ".join([
            r["state"], str(r["counties"]), str(r["edges_census"]),
            str(r["largest_clique_census"]), str(r["colors_needed_census"]),
            *[ms(r[f"ms_{a}_census"]) for a in ALGOS],
        ]) + " |")
    return "\n".join(lines) + "\n"


def plot(df, source, path, timeout_ms):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.ticker import FixedLocator, NullLocator

    d = df[df["source"] == source].sort_values("n").reset_index(drop=True)
    fig, ax = plt.subplots(figsize=(11, 15))

    for i in range(len(d)):  # zebra bands so each state's markers read as one row
        if i % 2 == 0:
            ax.axhspan(i - 0.5, i + 0.5, color="#f4f3ef", zorder=0, linewidth=0)

    for a in ALGOS:
        ok = d[d[f"ms_{a}"].notna()]
        ax.scatter(ok[f"ms_{a}"], ok.index, s=34, color=COLORS[a], marker=MARKERS[a],
                   edgecolor="white", linewidth=0.6, label=a, zorder=3)
        to = d[d[f"ms_{a}"].isna()]
        for i in to.index:
            ax.scatter(timeout_ms, i, s=60, color=COLORS[a], marker="X", zorder=4)
            ax.annotate(f"{a}: did not finish in {timeout_ms / 1000:.0f} s", (timeout_ms, i),
                        xytext=(-8, 0), textcoords="offset points", ha="right", va="center",
                        fontsize=7.5, color=INK)

    def count(k, one, many):
        return f"{k} {one if k == 1 else many}"

    labels = [f"{r.state}   {count(int(r.n), 'county', 'counties')} · "
              f"{count(int(r.m), 'edge', 'edges')} · clique {int(r.omega)}"
              for r in d.itertuples()]
    ax.set_yticks(range(len(d)), labels, fontsize=7.5, color=INK)
    ax.set_ylim(-0.7, len(d) - 0.3)

    ax.set_xscale("log")
    ticks = [0.001, 0.01, 0.1, 1, 10, 100, 1000, 10000, 60000]
    names = ["0.001 ms", "0.01 ms", "0.1 ms", "1 ms", "10 ms", "100 ms", "1 s", "10 s", "60 s"]
    ax.xaxis.set_major_locator(FixedLocator(ticks))
    ax.set_xticklabels(names)
    ax.xaxis.set_minor_locator(NullLocator())
    ax.set_xlim(0.0005, timeout_ms * 1.6)
    ax.tick_params(axis="x", colors=MUTED, labelsize=8)
    ax.tick_params(axis="y", length=0)
    ax.grid(True, axis="x", color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)
    for s in ("top", "right", "left"):
        ax.spines[s].set_visible(False)
    ax.spines["bottom"].set_color(GRID)
    ax.xaxis.set_ticks_position("both")
    ax.tick_params(axis="x", labeltop=True)

    ax.set_xlabel("median time for one coloring (log scale: each gridline is 10x slower)",
                  color=MUTED, fontsize=9)
    fig.suptitle("How long each algorithm takes to color each state's counties",
                 x=0.01, ha="left", fontsize=13, color=INK)
    ax.set_title(f"{LABELS[source]}. States sorted by number of counties.",
                 loc="left", fontsize=9, color=MUTED, pad=24)
    ax.legend(loc="lower right", frameon=True, facecolor="white", edgecolor=GRID,
              fontsize=8.5, title="algorithm", title_fontsize=8.5)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def main():
    df = pd.read_csv(METRICS)
    t = summary_table(df)
    t.to_csv(RESULTS / "state_summary.csv", index=False)
    (RESULTS / "state_summary.md").write_text(markdown(t))
    FIGS.mkdir(parents=True, exist_ok=True)
    timeout_ms = 60_000
    plot(df, "census", FIGS / "state_runtime_census.png", timeout_ms)
    plot(df, "tiger", FIGS / "state_runtime_rook.png", timeout_ms)
    print(f"wrote results/state_summary.csv, results/state_summary.md, "
          f"{FIGS}/state_runtime_census.png, {FIGS}/state_runtime_rook.png")


if __name__ == "__main__":
    main()
